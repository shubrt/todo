import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import { readFile, readdir, writeFile } from "node:fs/promises";

// The pinned Convex CLI requires a deployment even for codegen. Its API/server
// template functions are pure and can generate the same typed references locally.
const require = createRequire(import.meta.url);
const convexRoot = dirname(require.resolve("convex/package.json"));
const template = (name) =>
  import(pathToFileURL(resolve(convexRoot, `dist/esm/cli/codegen_templates/${name}.js`)).href);
const { apiCodegen } = await template("api");
const { serverCodegen } = await template("server");
const functionsDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "../convex");
const modules = (await readdir(functionsDirectory))
  .filter(
    (name) =>
      name.endsWith(".ts") &&
      !["schema.ts", "auth.config.ts", "crons.ts", "http.ts"].includes(name),
  )
  .sort();
const header = "// Generated by pnpm --filter @todo/backend codegen. Do not edit.\n";
const generated = {
  "api.ts": apiCodegen(modules, { useTypeScript: true }).TS,
  "server.ts": serverCodegen({ useTypeScript: true, envVars: undefined }).TS,
  "dataModel.ts": `${header}import type { DataModelFromSchemaDefinition, DocumentByName, TableNamesInDataModel, SystemTableNames } from 'convex/server';
import type { GenericId } from 'convex/values';
import type schema from '../schema.js';
export type DataModel = DataModelFromSchemaDefinition<typeof schema>;
export type TableNames = TableNamesInDataModel<DataModel>;
export type Doc<TableName extends TableNames> = DocumentByName<DataModel, TableName>;
export type Id<TableName extends TableNames | SystemTableNames> = GenericId<TableName>;
`,
};
for (const [name, content] of Object.entries(generated)) {
  if (typeof content !== "string")
    throw new Error(`Convex's codegen template for ${name} changed. Review the pinned version.`);
  const next = content.replaceAll("npx convex dev", "pnpm --filter @todo/backend codegen");
  const destination = resolve(functionsDirectory, "_generated", name);
  const previous = await readFile(destination, "utf8").catch(() => null);
  if (previous !== next) await writeFile(destination, next);
}
